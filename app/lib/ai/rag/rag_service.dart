/// Document chunk for RAG with citation metadata.
class DocumentChunk {
  final String id;
  final String documentId;
  final String content;
  final int chunkIndex;
  final Map<String, dynamic> metadata;
  final List<double>? embedding;

  // Citation metadata
  final int? pageNumber;
  final int? charStart;
  final int? charEnd;
  final String? sectionTitle;

  const DocumentChunk({
    required this.id,
    required this.documentId,
    required this.content,
    required this.chunkIndex,
    this.metadata = const {},
    this.embedding,
    this.pageNumber,
    this.charStart,
    this.charEnd,
    this.sectionTitle,
  });

  DocumentChunk copyWith({
    List<double>? embedding,
    int? pageNumber,
    int? charStart,
    int? charEnd,
    String? sectionTitle,
  }) =>
      DocumentChunk(
        id: id,
        documentId: documentId,
        content: content,
        chunkIndex: chunkIndex,
        metadata: metadata,
        embedding: embedding ?? this.embedding,
        pageNumber: pageNumber ?? this.pageNumber,
        charStart: charStart ?? this.charStart,
        charEnd: charEnd ?? this.charEnd,
        sectionTitle: sectionTitle ?? this.sectionTitle,
      );

  /// Generate a citation string for this chunk.
  String getCitation() {
    final parts = <String>[];
    if (sectionTitle != null && sectionTitle!.isNotEmpty) {
      parts.add(sectionTitle!);
    }
    if (pageNumber != null) {
      parts.add('p. $pageNumber');
    }
    if (charStart != null && charEnd != null) {
      parts.add('chars $charStart-$charEnd');
    }
    return parts.isEmpty ? 'Source' : parts.join(', ');
  }

  /// Get a short preview for citation tooltip.
  String getPreview({int maxLength = 120}) {
    final preview = content.replaceAll('\n', ' ').trim();
    if (preview.length <= maxLength) return preview;
    return '${preview.substring(0, maxLength)}...';
  }
}

/// Search result with relevance score and citation info.
class SearchResult {
  final DocumentChunk chunk;
  final double score;

  const SearchResult({required this.chunk, required this.score});

  /// Get citation for this result.
  String get citation => chunk.getCitation();

  /// Get preview for this result.
  String get preview => chunk.getPreview();
}

/// Internal helper for extractive summarization.
class _ScoredSentence {
  final int index;
  final String sentence;
  final double score;

  _ScoredSentence(this.index, this.sentence, this.score);
}

/// Citation reference for inline citations in responses.
class CitationRef {
  final int index; // 1-based index for [1], [2] style
  final String documentId;
  final String chunkId;
  final String citation;
  final String preview;
  final double score;

  const CitationRef({
    required this.index,
    required this.documentId,
    required this.chunkId,
    required this.citation,
    required this.preview,
    required this.score,
  });
}

