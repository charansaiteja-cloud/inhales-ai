/// Document chunk for RAG with citation metadata.
class DocumentChunk {
  final String id;
  final String documentId;
  final String content;
  final int chunkIndex;
  final Map<String, dynamic> metadata;
  final List<double>? embedding;

  // Citation metadata
  final int? pageNumber;
  final int? charStart;
  final int? charEnd;
  final String? sectionTitle;

  const DocumentChunk({
    required this.id,
    required this.documentId,
    required this.content,
    required this.chunkIndex,
    this.metadata = const {},
    this.embedding,
    this.pageNumber,
    this.charStart,
    this.charEnd,
    this.sectionTitle,
  });

  DocumentChunk copyWith({
    List<double>? embedding,
    int? pageNumber,
    int? charStart,
    int? charEnd,
    String? sectionTitle,
  }) => DocumentChunk(
    id: id,
    documentId: documentId,
    content: content,
    chunkIndex: chunkIndex,
    metadata: metadata,
    embedding: embedding ?? this.embedding,
    pageNumber: pageNumber ?? this.pageNumber,
    charStart: charStart ?? this.charStart,
    charEnd: charEnd ?? this.charEnd,
    sectionTitle: sectionTitle ?? this.sectionTitle,
  );

  /// Generate a citation string for this chunk.
  String getCitation() {
    final parts = <String>[];
    if (sectionTitle != null && sectionTitle!.isNotEmpty) {
      parts.add(sectionTitle!);
    }
    if (pageNumber != null) {
      parts.add('p. $pageNumber');
    }
    if (charStart != null && charEnd != null) {
      parts.add('chars $charStart-$charEnd');
    }
    return parts.isEmpty ? 'Source' : parts.join(', ');
  }

  /// Get a short preview for citation tooltip.
  String getPreview({int maxLength = 120}) {
    final preview = content.replaceAll('\n', ' ').trim();
    if (preview.length <= maxLength) return preview;
    return '${preview.substring(0, maxLength)}...';
  }
}

/// Search result with relevance score and citation info.
class SearchResult {
  final DocumentChunk chunk;
  final double score;

  const SearchResult({required this.chunk, required this.score});

  /// Get citation for this result.
  String get citation => chunk.getCitation();

  /// Get preview for this result.
  String get preview => chunk.getPreview();
}

/// Citation reference for inline citations in responses.
class CitationRef {
  final int index; // 1-based index for [1], [2] style
  final String documentId;
  final String chunkId;
  final String citation;
  final String preview;
  final double score;

  const CitationRef({
    required this.index,
    required this.documentId,
    required this.chunkId,
    required this.citation,
    required this.preview,
    required this.score,
  });
}

/// Document summary generated by AI.
class DocumentSummary {
  final String documentId;
  final String title;
  final String summary;
  final List<String> keyTopics;
  final List<String> suggestedQuestions;
  final DateTime generatedAt;

  const DocumentSummary({
    required this.documentId,
    required this.title,
    required this.summary,
    required this.keyTopics,
    required this.suggestedQuestions,
    required this.generatedAt,
  });
}

/// RAG Service for document retrieval using vector embeddings.
/// Currently uses hash-based embeddings with keyword fallback.
/// Can be extended with sqlite-vec when a stable Android build is available.
class RAGService {
  final AppDatabase _database;
  final AIEngine? _embeddingEngine;
  final List<DocumentChunk> _memoryIndex = [];
  bool _initialized = false;

  static const int _embeddingDim = 384; // BGE-small-en / E5-small dimension
  static const int _chunkSize = 512;
  static const int _chunkOverlap = 64;

  RAGService(this._database, {AIEngine? embeddingEngine})
    : _embeddingEngine = embeddingEngine;

  /// Initialize the RAG service.
  Future<void> initialize() async {
    if (_initialized) return;

    // Create documents table for storing chunks (simple approach without sqlite-vec)
    await _createDocumentChunksTable();

    // Load existing chunks into memory index
    await _loadIndex();

    _initialized = true;
  }

  Future<void> _createDocumentChunksTable() async {
    await _database.customStatement('''
      CREATE TABLE IF NOT EXISTS document_chunks (
        id TEXT PRIMARY KEY,
        document_id TEXT NOT NULL,
        chunk_index INTEGER NOT NULL,
        content TEXT NOT NULL,
        metadata TEXT,
        embedding TEXT, -- JSON array of floats
        created_at INTEGER NOT NULL DEFAULT (strftime('%s', 'now'))
      )
    ''');

    // Create index for faster document_id lookups
    await _database.customStatement('''
      CREATE INDEX IF NOT EXISTS idx_document_chunks_document_id
      ON document_chunks(document_id)
    ''');
  }

  /// Add a document to the index.
  Future<void> addDocument({
    required String documentId,
    required String title,
    required String content,
    Map<String, dynamic>? metadata,
  }) async {
    final chunks = _chunkText(content, documentId, title, metadata);
    await _indexChunks(chunks);
  }

  /// Search for relevant chunks using hybrid approach (vector + keyword).
  Future<List<SearchResult>> search(
    String query, {
    int limit = 5,
    double minScore = 0.3,
  }) async {
    return hybridSearch(query, limit: limit);
  }

  /// Search with hybrid approach (vector + keyword).
  Future<List<SearchResult>> hybridSearch(
    String query, {
    int limit = 5,
    double vectorWeight = 0.7,
    double keywordWeight = 0.3,
    double minScore = 0.3,
  }) async {
    final queryEmbedding = await _getEmbedding(query);

    final results = <SearchResult>[];

    for (final chunk in _memoryIndex) {
      double vectorScore = 0.0;
      if (queryEmbedding != null && chunk.embedding != null) {
        vectorScore = _cosineSimilarity(queryEmbedding, chunk.embedding!);
      }

      double keywordScore = _keywordScore(chunk.content, query);

      final score =
          (vectorScore * vectorWeight) + (keywordScore * keywordWeight);

      if (score >= minScore) {
        results.add(SearchResult(chunk: chunk, score: score));
      }
    }

    results.sort((a, b) => b.score.compareTo(a.score));
    return results.take(limit).toList();
  }

  double _cosineSimilarity(List<double> a, List<double> b) {
    if (a.length != b.length) return 0.0;

    double dot = 0.0, normA = 0.0, normB = 0.0;
    for (var i = 0; i < a.length; i++) {
      dot += a[i] * b[i];
      normA += a[i] * a[i];
      normB += b[i] * b[i];
    }
    final norm = math.sqrt(normA) * math.sqrt(normB);
    return norm > 0 ? dot / norm : 0.0;
  }

  double _keywordScore(String content, String query) {
    final contentLower = content.toLowerCase();
    final keywords =
        query
            .toLowerCase()
            .split(RegExp(r'\s+'))
            .where((w) => w.length > 1)
            .toList();
    if (keywords.isEmpty) return 0.0;

    var matches = 0;
    for (final kw in keywords) {
      if (contentLower.contains(kw)) matches++;
    }
    return matches / keywords.length;
  }

  /// Delete a document from the index.
  Future<void> deleteDocument(String documentId) async {
    await _database.customStatement(
      'DELETE FROM document_chunks WHERE document_id = ?',
      [documentId],
    );
    _memoryIndex.removeWhere((c) => c.documentId == documentId);
  }

  /// Get all indexed document IDs.
  Future<List<String>> getIndexedDocuments() async {
    final rows =
        await _database
            .customSelect('SELECT DISTINCT document_id FROM document_chunks')
            .get();

    return rows.map((r) => r.read<String>('document_id')).toList();
  }

  /// Clear all indexed documents.
  Future<void> clear() async {
    await _database.customStatement('DELETE FROM document_chunks');
    _memoryIndex.clear();
  }

  // ── Private helpers ────────────────────────────────────────

  List<DocumentChunk> _chunkText(
    String text,
    String documentId,
    String title,
    Map<String, dynamic>? metadata,
  ) {
    final chunks = <DocumentChunk>[];
    const overlap = _chunkOverlap;

    for (var i = 0; i < text.length; i += _chunkSize - overlap) {
      final end = math.min(i + _chunkSize, text.length);
      final chunkText = text.substring(i, end).trim();
      if (chunkText.isEmpty) continue;

      chunks.add(
        DocumentChunk(
          id: '${documentId}_chunk_${chunks.length}',
          documentId: documentId,
          content: chunkText,
          chunkIndex: chunks.length,
          metadata: {
            'title': title,
            'source': metadata?['source'] ?? 'unknown',
            'timestamp': DateTime.now().toIso8601String(),
          },
        ),
      );
    }

    return chunks;
  }

  Future<void> _indexChunks(List<DocumentChunk> chunks) async {
    // Generate embeddings for chunks
    final chunksWithEmbeddings = <DocumentChunk>[];
    for (final chunk in chunks) {
      final embedding = await _getEmbedding(chunk.content);
      if (embedding != null) {
        chunksWithEmbeddings.add(chunk.copyWith(embedding: embedding));
      }
    }

    if (chunksWithEmbeddings.isEmpty) return;

    // Batch insert into document_chunks table
    await _database.batch((b) {
      for (final chunk in chunksWithEmbeddings) {
        b.customStatement(
          '''
          INSERT OR REPLACE INTO document_chunks
          (id, document_id, chunk_index, content, metadata, embedding, created_at)
          VALUES (?, ?, ?, ?, ?, ?, ?)
        ''',
          [
            chunk.id,
            chunk.documentId,
            chunk.chunkIndex,
            chunk.content,
            jsonEncode(chunk.metadata),
            jsonEncode(chunk.embedding!),
            DateTime.now().millisecondsSinceEpoch ~/ 1000,
          ],
        );
      }
    });

    // Update memory index
    _memoryIndex.addAll(chunksWithEmbeddings);
  }

  Future<void> _loadIndex() async {
    final rows =
        await _database.customSelect('''
      SELECT id, document_id, chunk_index, content, metadata, embedding
      FROM document_chunks
    ''').get();

    _memoryIndex.clear();
    for (final row in rows) {
      List<double>? embedding;
      final embeddingJson = row.read<String>('embedding');
      if (embeddingJson.isNotEmpty) {
        try {
          final List<dynamic> decoded = jsonDecode(embeddingJson);
          embedding = decoded.map((e) => (e as num).toDouble()).toList();
        } catch (_) {}
      }

      Map<String, dynamic> metadata = {};
      final metadataJson = row.read<String>('metadata');
      if (metadataJson.isNotEmpty) {
        try {
          metadata = jsonDecode(metadataJson);
        } catch (_) {}
      }

      _memoryIndex.add(
        DocumentChunk(
          id: row.read<String>('id'),
          documentId: row.read<String>('document_id'),
          content: row.read<String>('content'),
          chunkIndex: row.read<int>('chunk_index'),
          metadata: metadata,
          embedding: embedding,
        ),
      );
    }
  }

  Future<List<double>?> _getEmbedding(String text) async {
    if (_embeddingEngine == null) return _hashEmbedding(text);

    try {
      // Use a small embedding model prompt
      // For now, fall back to a simple hash-based embedding
      return _hashEmbedding(text);
    } catch (e) {
      return _hashEmbedding(text);
    }
  }

  /// Deterministic hash-based embedding (fallback when no embedding model available).
  List<double> _hashEmbedding(String text) {
    final hash = _simpleHash(text);
    final embedding = <double>[];
    for (var i = 0; i < _embeddingDim; i++) {
      final byte = hash[i % hash.length];
      embedding.add((byte / 255.0) * 2 - 1); // Normalize to [-1, 1]
    }
    // Normalize to unit vector
    final norm = math.sqrt(embedding.map((x) => x * x).reduce((a, b) => a + b));
    return embedding.map((x) => x / (norm + 1e-8)).toList();
  }

  List<int> _simpleHash(String input) {
    // DJB2 hash algorithm - produces different hashes for different inputs
    int h1 = 5381;
    int h2 = 0;
    for (final codeUnit in input.codeUnits) {
      h1 = ((h1 << 5) + h1 + codeUnit) & 0xffffffff;
      h2 = ((h2 << 5) + h2 + (codeUnit ^ 0xff)) & 0xffffffff;
    }
    // Generate 32 bytes from two hash values
    return List.generate(32, (i) {
      if (i < 4) return (h1 >> (i * 8)) & 0xff;
      return (h2 >> ((i - 4) * 8)) & 0xff;
    });
  }

  // ── Enhanced chunking with citation metadata ──────────────────

  /// Chunk text with page/section awareness for PDF documents.
  List<DocumentChunk> chunkTextWithCitations({
    required String text,
    required String documentId,
    required String title,
    Map<String, dynamic>? metadata,
    List<int>? pageBreaks, // Character indices where pages start
    Map<int, String>? sectionTitles, // charIndex -> section title
  }) {
    final chunks = <DocumentChunk>[];
    const overlap = _chunkOverlap;

    // Determine page number for a character position
    int getPageNumber(int pos) {
      if (pageBreaks == null || pageBreaks.isEmpty) return 1;
      for (var i = pageBreaks.length - 1; i >= 0; i--) {
        if (pos >= pageBreaks[i]) return i + 1;
      }
      return 1;
    }

    // Determine section title for a character position
    String? getSectionTitle(int pos) {
      if (sectionTitles == null || sectionTitles.isEmpty) return null;
      String? currentSection;
      for (final entry in sectionTitles.entries) {
        if (entry.key <= pos) {
          currentSection = entry.value;
        } else {
          break;
        }
      }
      return currentSection;
    }

    for (var i = 0; i < text.length; i += _chunkSize - overlap) {
      final end = math.min(i + _chunkSize, text.length);
      final chunkText = text.substring(i, end).trim();
      if (chunkText.isEmpty) continue;

      final pageNum = getPageNumber(i);
      final section = getSectionTitle(i);

      chunks.add(
        DocumentChunk(
          id: '${documentId}_chunk_${chunks.length}',
          documentId: documentId,
          content: chunkText,
          chunkIndex: chunks.length,
          metadata: {
            'title': title,
            'source': metadata?['source'] ?? 'unknown',
            'timestamp': DateTime.now().toIso8601String(),
          },
          pageNumber: pageNum,
          charStart: i,
          charEnd: end,
          sectionTitle: section,
        ),
      );
    }

    return chunks;
  }

  /// Get all chunks for a specific document (with citation info).
  Future<List<DocumentChunk>> getDocumentChunks(String documentId) async {
    final rows =
        await _database
            .customSelect(
              '''
      SELECT id, document_id, chunk_index, content, metadata, embedding
      FROM document_chunks
      WHERE document_id = ?
      ORDER BY chunk_index
    ''',
              variables: [Variable.withString(documentId)],
            )
            .get();

    final chunks = <DocumentChunk>[];
    for (final row in rows) {
      List<double>? embedding;
      final embeddingJson = row.read<String>('embedding');
      if (embeddingJson.isNotEmpty) {
        try {
          final List<dynamic> decoded = jsonDecode(embeddingJson);
          embedding = decoded.map((e) => (e as num).toDouble()).toList();
        } catch (_) {}
      }

      Map<String, dynamic> metadata = {};
      final metadataJson = row.read<String>('metadata');
      if (metadataJson.isNotEmpty) {
        try {
          metadata = jsonDecode(metadataJson);
        } catch (_) {}
      }

      chunks.add(
        DocumentChunk(
          id: row.read<String>('id'),
          documentId: row.read<String>('document_id'),
          content: row.read<String>('content'),
          chunkIndex: row.read<int>('chunk_index'),
          metadata: metadata,
          embedding: embedding,
          pageNumber: null,
          charStart: null,
          charEnd: null,
          sectionTitle: null,
        ),
      );
    }

    return chunks;
  }

  // ── Document Q&A with Citations ──────────────────────────────

  /// Answer a question using document context with citations.
  /// Returns answer text and list of citations used.
  Future<({String answer, List<CitationRef> citations})> answerWithCitations(
    String query, {
    String? documentId,
    int limit = 5,
    AIEngine? generationEngine,
  }) async {
    // Search for relevant chunks
    final results =
        documentId != null
            ? await searchInDocument(query, documentId, limit: limit)
            : await hybridSearch(query, limit: limit);

    if (results.isEmpty) {
      return (
        answer:
            'I couldn\'t find relevant information in the uploaded documents.',
        citations: <CitationRef>[],
      );
    }

    // Build context from top chunks
    final contextChunks = results.take(limit).toList();
    final context = contextChunks
        .map((r) => '[${r.chunk.chunkIndex + 1}] ${r.chunk.content}')
        .join('\n\n');

    // Create citation references
    final citations =
        contextChunks.asMap().entries.map((entry) {
          final idx = entry.key + 1;
          final result = entry.value;
          return CitationRef(
            index: idx,
            documentId: result.chunk.documentId,
            chunkId: result.chunk.id,
            citation: result.citation,
            preview: result.preview,
            score: result.score,
          );
        }).toList();

    // Generate answer with citations
    String answer;
    if (generationEngine != null) {
      final prompt = '''Answer the question using ONLY the provided context. 
Cite sources using [1], [2], etc. corresponding to the numbered context chunks.
If the answer is not in the context, say so.

Context:
$context

Question: $query

Answer:''';

      final buffer = StringBuffer();
      await for (final chunk in generationEngine.generate(
        prompt: prompt,
        history: [],
        systemPrompt:
            'You are a document Q&A assistant. Answer based only on provided context. Use inline citations [1], [2], etc.',
        maxTokens: 512,
        temperature: 0.3,
        topP: 0.9,
      )) {
        buffer.write(chunk);
      }
      answer = buffer.toString().trim();
    } else {
      // Fallback: return top chunks as answer
      answer =
          'Based on the document(s):\n\n' +
          contextChunks
              .map(
                (r) =>
                    '• ${r.chunk.content.substring(0, math.min(200, r.chunk.content.length))}...',
              )
              .join('\n\n');
    }

    return (answer: answer, citations: citations);
  }

  /// Search within a specific document.
  Future<List<SearchResult>> searchInDocument(
    String query,
    String documentId, {
    int limit = 5,
    double minScore = 0.2,
  }) async {
    final queryEmbedding = await _getEmbedding(query);

    final results = <SearchResult>[];
    for (final chunk in _memoryIndex) {
      if (chunk.documentId != documentId) continue;

      double vectorScore = 0.0;
      if (queryEmbedding != null && chunk.embedding != null) {
        vectorScore = _cosineSimilarity(queryEmbedding, chunk.embedding!);
      }

      double keywordScore = _keywordScore(chunk.content, query);

      final score = (vectorScore * 0.7) + (keywordScore * 0.3);

      if (score >= minScore) {
        results.add(SearchResult(chunk: chunk, score: score));
      }
    }

    results.sort((a, b) => b.score.compareTo(a.score));
    return results.take(limit).toList();
  }

  // ── AI-Generated Document Summaries ──────────────────────────

  /// Generate AI summary of a document with key topics and suggested questions.
  Future<DocumentSummary?> generateDocumentSummary(
    String documentId, {
    AIEngine? generationEngine,
  }) async {
    if (generationEngine == null) return null;

    final chunks = await getDocumentChunks(documentId);
    if (chunks.isEmpty) return null;

    // Combine first few chunks for summary (or all if small)
    final content = chunks.take(10).map((c) => c.content).join('\n\n');

    final prompt = '''Analyze this document and provide:
1. A concise summary (3-5 sentences)
2. 5-7 key topics/themes
3. 5 suggested questions a student might ask

Document title: ${chunks.first.metadata['title'] ?? 'Unknown'}
Content:
$content

Format as JSON:
{
  "summary": "...",
  "keyTopics": ["...", "..."],
  "suggestedQuestions": ["...", "..."]
}''';

    final buffer = StringBuffer();
    await for (final chunk in generationEngine.generate(
      prompt: prompt,
      history: [],
      systemPrompt:
          'You are a document analysis assistant. Output valid JSON only.',
      maxTokens: 512,
      temperature: 0.4,
      topP: 0.9,
    )) {
      buffer.write(chunk);
    }

    try {
      final json = jsonDecode(buffer.toString().trim());
      return DocumentSummary(
        documentId: documentId,
        title: chunks.first.metadata['title'] ?? 'Unknown',
        summary: json['summary'] ?? '',
        keyTopics: List<String>.from(json['keyTopics'] ?? []),
        suggestedQuestions: List<String>.from(json['suggestedQuestions'] ?? []),
        generatedAt: DateTime.now(),
      );
    } catch (_) {
      // Fallback
      return DocumentSummary(
        documentId: documentId,
        title: chunks.first.metadata['title'] ?? 'Unknown',
        summary: content.substring(0, math.min(300, content.length)),
        keyTopics: [],
        suggestedQuestions: [
          'What is the main idea of this document?',
          'Can you explain the key concepts?',
          'What are the important takeaways?',
        ],
        generatedAt: DateTime.now(),
      );
    }
  }

  // ── Study Material Generation ────────────────────────────────

  /// Generate study materials from a document (flashcard-style Q&A).
  Future<List<({String question, String answer, String citation})>>
  generateStudyQA(
    String documentId, {
    int count = 10,
    AIEngine? generationEngine,
  }) async {
    if (generationEngine == null) return [];

    final chunks = await getDocumentChunks(documentId);
    if (chunks.isEmpty) return [];

    final content = chunks
        .take(15)
        .map((c) => '[${c.chunkIndex + 1}] ${c.content}')
        .join('\n\n');

    final prompt =
        '''Generate $count study questions and answers from this document.
Each Q&A should be self-contained and educational.
Include the source chunk number [N] for each answer.

Document: ${chunks.first.metadata['title'] ?? 'Unknown'}
Content:
$content

Format as JSON array:
[
  {"question": "...", "answer": "...", "sourceChunk": 1},
  ...
]''';

    final buffer = StringBuffer();
    await for (final chunk in generationEngine.generate(
      prompt: prompt,
      history: [],
      systemPrompt:
          'You are a study material generator. Output valid JSON array only.',
      maxTokens: 1024,
      temperature: 0.5,
      topP: 0.9,
    )) {
      buffer.write(chunk);
    }

    try {
      final json = jsonDecode(buffer.toString().trim());
      return (json as List).map((item) {
        final chunkIdx = item['sourceChunk'] as int? ?? 1;
        final sourceChunk = chunks.firstWhere(
          (c) => c.chunkIndex == chunkIdx - 1,
          orElse: () => chunks.first,
        );
        return (
          question: item['question'] as String,
          answer: item['answer'] as String,
          citation: sourceChunk.getCitation(),
        );
      }).toList();
    } catch (_) {
      return [];
    }
  }
}
